function makeOrder(
  id: string,
  userId: string,
  userName: string,
  lines: { bookId: string; qty: number }[],
  status: OrderStatus,
  date: string,
  address: string
): Order {
  const items: OrderItem[] = lines.map(({ bookId, qty }) => {
    const book = initialBooks.find((b) => b.id === bookId)!;
    return {
      bookId,
      title: book.title,
      price: book.offPrice ?? book.price,
      qty,
      img: book.img,
    };
  });
  const total = items.reduce((sum, item) => sum + item.price * item.qty, 0);
  return { id, userId, userName, items, total, status, date, address };
}

